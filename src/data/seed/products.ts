function stockFromDef(def: StockDef, now: Date): Product["inventory"] {
  const [status] = def;
  const base = { status: status as StockStatus, quantity: 0, lowStockThreshold: 10 };
  switch (def[0]) {
    case "in_stock":
      return { ...base, quantity: def[1] };
    case "low_stock":
      return { ...base, quantity: def[1] };
    case "out_of_stock":
      return {
        ...base,
        quantity: 0,
        restockDate: def[1] ? new Date(now.getTime() + def[1] * 86400000).toISOString() : undefined,
      };
    case "special_order":
      return { ...base, quantity: 0, leadTime: def[1] };
  }
}

export function buildProducts(now = new Date()): Product[] {
  const counters: Record<string, number> = {};
  const idFor = (key: string) => `prd_${key}`;

  return defs.map((def, index) => {
    const code = categoryCode[def.category];
    counters[code] = (counters[code] ?? 1000) + 10;
    const slug = def.slug ?? slugify(def.name.replace(/—.*$/, "").replace(/"/g, "in"));
    const created = new Date(now.getTime() - (defs.length - index) * 86400000 * 2).toISOString();
    const [retail, sale, contractor] = def.price;
    const images = def.photos
      ? def.photos.map((p) => ({ src: `/media/products/${slug}/${p.file}`, alt: p.alt }))
      : [
          { src: `/media/products/${slug}/1.svg`, alt: `${def.name} — product view` },
          { src: `/media/products/${slug}/2.svg`, alt: `${def.name} — detail view` },
        ];
    if (!def.photos && supportsRoomView(def.art[0], def.art[3])) {
      images.push({ src: `/media/products/${slug}/3.svg`, alt: `${def.name} — shown in a room setting` });
    }
    const documents: ProductDocument[] = (def.docs ?? []).map((d) => ({
      id: d,
      name: docLabels[d].name,
      kind: docLabels[d].kind,
      url: `/media/docs/${slug}/${d}.pdf`,
      sizeKb: docLabels[d].sizeKb,
    }));

    return {
      id: idFor(def.key),
      slug,
      name: def.name,
      categoryId: def.category,
      subcategory: def.sub,
      sku: def.sku ?? `${code}-${counters[code]}`,
      brand: def.brand,
      shortDescription: def.short,
      description: def.description,
      features: def.features,
      pricing: {
        retail,
        sale,
        contractor,
        visibility: def.visibility ?? "public",
        unit: def.unit ?? "each",
        saleEndsAt:
          sale !== null && def.saleEndsInDays
            ? new Date(now.getTime() + def.saleEndsInDays * 86400000).toISOString()
            : undefined,
      },
      inventory: stockFromDef(def.stock, now),
      coverage: def.coverage ? { type: "area", ...def.coverage } : undefined,
      attributes: def.attrs ?? {},
      specifications: def.specs.map(([label, value]) => ({ label, value })),
      installation: categoryInstall[def.category],
      warranty: categoryWarranty[def.category],
      images,
      art: { kind: def.art[0], primary: def.art[1], secondary: def.art[2], variant: def.art[3] },
      documents,
      variants: def.variants ?? [],
      relatedIds: (def.related ?? []).map(idFor),
      accessoryIds: (def.accessories ?? []).map(idFor),
      minOrderQty: def.minOrderQty,
      oversized: def.oversized,
      badges: def.badges ?? [],
      featured: def.featured ?? false,
      active: true,
      createdAt: created,
      updatedAt: created,
    } satisfies Product;
  });
}
